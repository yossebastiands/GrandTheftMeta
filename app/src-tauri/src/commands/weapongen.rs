struct Built {
    /// Relative path → content.
    files: Vec<(String, String, String)>, // (rel path, kind, content)
    stream: Vec<String>,
    retargets: Vec<String>,
    edits: Vec<String>,
    conflicts: Vec<String>,
    warnings: Vec<String>,
}

fn sibling(dir: &Path, kind: FileKind) -> Option<PathBuf> {
    let entries = fs::read_dir(dir).ok()?;
    let mut best: Option<PathBuf> = None;
    for entry in entries.flatten() {
        let path = entry.path();
        if !path.is_file() {
            continue;
        }
        if file_kind(&entry.file_name().to_string_lossy()) == Some(kind) {
            // exact names win; `*_` variants are the fallback
            let name = entry.file_name().to_string_lossy().to_ascii_lowercase();
            if name == "weaponanimations.meta" || name == "pedpersonality.meta" {
                return Some(path);
            }
            best.get_or_insert(path);
        }
    }
    best
}

/// Build everything for one weapon. Pure apart from reading the files the spec points at.
fn build_weapon(spec: &WeaponSpec) -> Result<Built, String> {
    let mut conflicts: Vec<String> = Vec::new();
    let mut warnings: Vec<String> = Vec::new();
    let mut edits: Vec<String> = Vec::new();
    let mut retargets: Vec<String> = Vec::new();
    let mut files: Vec<(String, String, String)> = Vec::new();

    // --- validate the spec -------------------------------------------------
    if !id_re().is_match(&spec.id) {
        conflicts.push(format!("weapon id '{}' must match WEAPON_[A-Z0-9_]+", spec.id));
    }
    if spec.display_name.trim().is_empty() {
        conflicts.push("display name is empty (cl_weaponNames.lua would show the raw id)".into());
    }
    if spec.slot_order.is_none() {
        warnings.push(format!(
            "no slot order set — defaulted to {DEFAULT_SLOT_ORDER}; the weapon wheel order may collide with another add-on"
        ));
    }
    let template_meta = PathBuf::from(&spec.template_meta_path);
    let Some(template_dir) = template_meta.parent() else {
        return Err("template path has no parent folder".into());
    };

    // --- assets ------------------------------------------------------------
    let assets = match spec.assets_folder.as_deref() {
        Some(folder) if !folder.trim().is_empty() => scan_weapon_assets(folder.to_string())?,
        _ => Vec::new(),
    };
    if assets.is_empty() {
        warnings.push("no assets folder set — weaponarchetypes.meta will be an empty stub and nothing is copied to stream/".into());
    }
    let main = spec
        .model
        .clone()
        .or_else(|| main_drawable(&assets));
    if spec.model.is_none() && main.is_none() {
        warnings.push("no model chosen and no drawable found — `<Model>` keeps the template's value".into());
    }

    // --- animations + personality -----------------------------------------
    for (kind, label) in [
        (FileKind::Animations, "weaponanimations.meta"),
        (FileKind::PedPersonality, "pedpersonality.meta"),
    ] {
        let Some(path) = sibling(template_dir, kind) else {
            conflicts.push(format!("{label} not found next to the template weapons.meta"));
            continue;
        };
        let text = fs::read_to_string(&path).map_err(|e| format!("{}: {e}", path.display()))?;
        let ids = weapon_ids_in_file(&text);
        if ids.len() > MAX_TEMPLATE_IDS {
            conflicts.push(format!(
                "{} names {} weapons — that is a shared vanilla file, not a per-weapon template. \
                 Point at a per-weapon folder (e.g. a pack's metas/<weapon>/) or split it first.",
                path.file_name().unwrap_or_default().to_string_lossy(),
                ids.len()
            ));
            continue;
        }
        let rel = format!("metas/{}/{}", weapon_slug(&spec.id), label);
        if kind == FileKind::Animations {
            let mut owned = text.clone();
            if let Some(value) = &spec.fire_rate_modifier {
                let n = set_anim_fire_rate(&mut owned, value);
                if n > 0 {
                    edits.push(format!("AnimFireRateModifier → {value} in {n} personality set(s)"));
                } else {
                    warnings.push("no <AnimFireRateModifier> found to patch".into());
                }
            }
            let out = retarget_file(&owned, &spec.id);
            for (id, n) in ids {
                retargets.push(format!("{}: {id} ×{n} → {}", label, spec.id));
            }
            files.push((rel, "animations".into(), out));
        } else {
            let out = retarget_file(&text, &spec.id);
            for (id, n) in ids {
                retargets.push(format!("{label}: {id} ×{n} → {}", spec.id));
            }
            files.push((rel, "personality".into(), out));
        }
    }

    // --- components --------------------------------------------------------
    let mut attach: Vec<AttachSpec> = Vec::new();
    let mut seen_names: BTreeSet<String> = BTreeSet::new();
    for comp in &spec.components {
        if !seen_names.insert(comp.name.clone()) {
            conflicts.push(format!("component '{}' listed twice", comp.name));
            continue;
        }
        let source = match fs::read_to_string(&comp.source_file) {
            Ok(t) => t,
            Err(e) => {
                conflicts.push(format!("component source {}: {e}", comp.source_file));
                continue;
            }
        };
        match build_component_meta(&source, &comp.source_name, comp) {
            Ok((text, bone, comp_edits)) => {
                if bone.is_empty() {
                    warnings.push(format!(
                        "component '{}' has no <WeaponAttachBone> — it cannot be attached to a bone",
                        comp.name
                    ));
                }
                edits.extend(comp_edits);
                attach.push(AttachSpec { name: comp.name.clone(), bone, default: comp.default });
                files.push((
                    format!("metas/{}/components/{}/weaponcomponents.meta", weapon_slug(&spec.id), comp.name),
                    "component".into(),
                    text,
                ));
            }
            Err(e) => conflicts.push(e),
        }
    }

    // --- weapons.meta ------------------------------------------------------
    let (slots, slot_warnings) = group_attach_slots(&attach);
    warnings.extend(slot_warnings);
    if !spec.components.is_empty() && slots.is_empty() {
        conflicts.push(
            "no component declares a <WeaponAttachBone>, so the weapon would have no attachment slots"
                .into(),
        );
    }
    let template_text = fs::read_to_string(&template_meta)
        .map_err(|e| format!("{}: {e}", template_meta.display()))?;
    match build_weapons_meta(&template_text, &spec.template_id, spec, &slots, main.as_deref()) {
        Ok((text, weapon_edits, weapon_warnings)) => {
            edits.extend(weapon_edits);
            warnings.extend(weapon_warnings);
            // The pickup hash is intentionally inherited: there is no pickup definition for
            // a brand-new id, and pointing at a non-existent one is worse than sharing the
            // vanilla pickup — but the author should know.
            if text.contains(&format!("PICKUP_{}", spec.template_id)) {
                warnings.push(format!(
                    "<PickupHash> still points at PICKUP_{} (the game has no pickup for {}); add a pickup definition if the weapon needs its own ground model",
                    spec.template_id, spec.id
                ));
            }
            files.push((
                format!("metas/{}/weapons.meta", weapon_slug(&spec.id)),
                "weapons".into(),
                text,
            ));
        }
        Err(e) => conflicts.push(e),
    }

    // --- archetypes --------------------------------------------------------
    files.push((
        format!("metas/{}/weaponarchetypes.meta", weapon_slug(&spec.id)),
        "archetypes".into(),
        build_weaponarchetypes(&assets, main.as_deref()),
    ));

    // --- manifest + names --------------------------------------------------
    files.push(("fxmanifest.lua".into(), "manifest".into(), manifest_text()));
    files.push((
        "cl_weaponNames.lua".into(),
        "lua".into(),
        format!("{}{}", lua_header(), lua_entry(&spec.id, &spec.display_name)),
    ));

    let stream: Vec<String> = assets.iter().map(|a| a.path.clone()).collect();
    // dedupe by relative target
    let mut seen_targets: BTreeSet<String> = BTreeSet::new();
    files.retain(|(rel, _, _)| seen_targets.insert(rel.clone()));

    Ok(Built { files, stream, retargets, edits, conflicts, warnings })
}

fn plan_for(built: &Built, out: &Path, folder: &str) -> ExportPlan {
    let mut files: Vec<PlannedFile> = Vec::new();
    let mut total = 0usize;
    for (rel, kind, content) in &built.files {
        let path = out.join(rel);
        let action = if kind == "lua" && path.is_file() {
            "append"
        } else if path.is_file() {
            "update"
        } else {
            "create"
        };
        total += content.len();
        files.push(PlannedFile {
            path: path.to_string_lossy().into_owned(),
            action: action.into(),
            kind: kind.clone(),
            bytes: content.len(),
        });
    }
    for src in &built.stream {
        let name = Path::new(src).file_name().unwrap_or_default().to_string_lossy().to_string();
        let target = out.join("stream").join(folder).join(&name);
        total += fs::metadata(src).map(|m| m.len() as usize).unwrap_or(0);
        files.push(PlannedFile {
            path: target.to_string_lossy().into_owned(),
            action: "copy".into(),
            kind: "stream".into(),
            bytes: fs::metadata(src).map(|m| m.len() as usize).unwrap_or(0),
        });
    }
    // stream sources are resolved relative to the assets folder the spec points at

    ExportPlan {
        out_root: out.to_string_lossy().into_owned(),
        folder: folder.to_string(),
        files,
        retargeted: built.retargets.clone(),
        edits: built.edits.clone(),
        conflicts: built.conflicts.clone(),
        warnings: built.warnings.clone(),
        total_bytes: total,
    }
}

/// Conflicts that depend on the *target* folder (existing resource, foreign manifest, …).
fn target_conflicts(out: &Path, spec: &WeaponSpec, overwrite: bool) -> Vec<String> {
    let mut out_conflicts = Vec::new();
    let folder = out.join("metas").join(weapon_slug(&spec.id));
    if folder.exists() && !overwrite {
        out_conflicts.push(format!(
            "{} already exists — pick another id or enable overwrite",
            folder.display()
        ));
    }
    let manifest = out.join("fxmanifest.lua");
    if manifest.is_file() {
        match fs::read_to_string(&manifest) {
            Ok(text) if text.contains(MANIFEST_MARKER) => {}
            Ok(_) => out_conflicts
                .push("fxmanifest.lua exists and was not written by GrandTheftMeta — refusing to touch it".into()),
            Err(e) => out_conflicts.push(format!("fxmanifest.lua: {e}")),
        }
    }
    let lua = out.join("cl_weaponNames.lua");
    if lua.is_file() {
        match fs::read_to_string(&lua) {
            Ok(text) if text.contains(MANIFEST_MARKER) || text.contains("GrandTheftMeta") => {}
            Ok(_) => out_conflicts
                .push("cl_weaponNames.lua exists and was not written by GrandTheftMeta — refusing to touch it".into()),
            Err(e) => out_conflicts.push(format!("cl_weaponNames.lua: {e}")),
        }
    }
    out_conflicts
}

/// Dry run for ONE weapon: exactly the files/edits the pack writer produces for it.
/// The pack-level preview (`preview_weapon_pack`) is what the writer is driven by.
#[tauri::command]
pub fn preview_weapon_export(spec: WeaponSpec, out_folder: String) -> Result<ExportPlan, String> {
    let built = build_weapon(&spec)?;
    let out = PathBuf::from(&out_folder);
    let mut plan = plan_for(&built, &out, &weapon_slug(&spec.id));
    plan.conflicts.extend(target_conflicts(&out, &spec, false));
    Ok(plan)
}

