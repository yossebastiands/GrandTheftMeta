/// One streamed file found next to the model, classified by what the generator would
/// use it for.
#[derive(Serialize, Debug, Clone, Default)]
pub struct WeaponAsset {
    /// Relative path inside the picked folder.
    pub file: String,
    pub path: String,
    /// `drawable` | `texture`.
    pub kind: String,
    /// `main` | `lod` | `mag1` | `mag2` | `flashlight` | `suppressor` | `scope` | `grip`
    /// | `rail` | `attachment` | `texture`.
    pub role: String,
    /// File name without extension.
    pub stem: String,
    /// `stem` with a `_hi` / `+hi` LOD suffix removed.
    pub drawable: String,
    pub bytes: u64,
}

fn mag_re() -> &'static Regex {
    static RE: OnceLock<Regex> = OnceLock::new();
    RE.get_or_init(|| Regex::new(r"(?i)(?:mag|clip)[_ ]?0?([12])$").expect("mag regex"))
}

fn attachment_role(lower: &str) -> Option<&'static str> {
    for (needle, role) in [
        ("flsh", "flashlight"),
        ("flash", "flashlight"),
        ("supp", "suppressor"),
        ("silenc", "suppressor"),
        ("scope", "scope"),
        ("grip", "grip"),
        ("rail", "rail"),
    ] {
        if lower.contains(needle) {
            return Some(role);
        }
    }
    if lower.starts_with("w_at_") {
        return Some("attachment");
    }
    None
}

/// `stem` without a high-LOD suffix (`w_pi_m4_hi` → `w_pi_m4`).
pub(crate) fn strip_lod(stem: &str) -> String {
    let lower = stem.to_ascii_lowercase();
    for suffix in ["_hi", "+hi"] {
        if lower.ends_with(suffix) {
            return stem[..stem.len() - suffix.len()].to_string();
        }
    }
    stem.to_string()
}

/// Classify one file name → `(kind, role, stem, drawable)`, or `None` when it is not a
/// drawable/texture we care about.
pub(crate) fn classify_asset(name: &str) -> Option<(String, String, String, String)> {
    let lower = name.to_ascii_lowercase();
    let (stem, ext) = name.rsplit_once('.')?;
    if ext.eq_ignore_ascii_case("ytd") {
        let drawable = strip_lod(stem);
        return Some(("texture".into(), "texture".into(), stem.to_string(), drawable));
    }
    if !ext.eq_ignore_ascii_case("ydr") {
        return None;
    }
    let drawable = strip_lod(stem);
    let role = if stem != drawable {
        "lod"
    } else if let Some(c) = mag_re().captures(stem) {
        if &c[1] == "1" {
            "mag1"
        } else {
            "mag2"
        }
    } else {
        attachment_role(&lower).unwrap_or("main")
    };
    Some(("drawable".into(), role.into(), stem.to_string(), drawable))
}

/// Scan a folder for weapon assets (recursively).
#[tauri::command]
pub fn scan_weapon_assets(folder_path: String) -> Result<Vec<WeaponAsset>, String> {
    let root = PathBuf::from(&folder_path);
    if !root.is_dir() {
        return Err(format!("Folder not found: {folder_path}"));
    }
    let mut out = Vec::new();
    for entry in WalkDir::new(&root).follow_links(false).into_iter().flatten() {
        if !entry.file_type().is_file() {
            continue;
        }
        let name = entry.file_name().to_string_lossy().to_string();
        let Some((kind, role, stem, drawable)) = classify_asset(&name) else {
            continue;
        };
        let path = entry.path();
        out.push(WeaponAsset {
            file: path
                .strip_prefix(&root)
                .unwrap_or(path)
                .to_string_lossy()
                .replace('\\', "/"),
            path: path.to_string_lossy().into_owned(),
            kind,
            role,
            stem,
            drawable,
            bytes: entry.metadata().map(|m| m.len()).unwrap_or(0),
        });
    }
    out.sort_by(|a, b| a.file.cmp(&b.file));
    Ok(out)
}

/// The model a weapon should point at: the biggest `main` drawable (its largest file is
/// the one the author most likely authored as the gun itself).
pub(crate) fn main_drawable(assets: &[WeaponAsset]) -> Option<String> {
    assets
        .iter()
        .filter(|a| a.role == "main")
        .max_by_key(|a| a.bytes)
        .map(|a| a.drawable.clone())
}

