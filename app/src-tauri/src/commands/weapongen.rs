const PRESET_APP: &str = "GrandTheftMeta";
const PRESET_VERSION: u32 = 1;

/// A saved editor state: every queued weapon plus the output folder. Plain JSON so it can be
/// committed next to the resource, diffed, or handed to someone else — the original tool's
/// "state" was a `SLOT` counter file and nothing else.
#[derive(Deserialize, Serialize, Debug, Clone, Default)]
pub struct WeaponPreset {
    /// `GrandTheftMeta` — a cheap guard against loading an unrelated JSON file.
    pub app: String,
    pub version: u32,
    pub out_folder: Option<String>,
    pub weapons: Vec<WeaponSpec>,
}

#[tauri::command]
pub fn save_weapon_preset(weapons: Vec<WeaponSpec>, out_folder: Option<String>, path: String) -> Result<String, String> {
    if weapons.is_empty() {
        return Err("nothing to save — the pack is empty".into());
    }
    let preset = WeaponPreset {
        app: PRESET_APP.into(),
        version: PRESET_VERSION,
        out_folder,
        weapons,
    };
    let text = serde_json::to_string_pretty(&preset).map_err(|e| e.to_string())?;
    let file = PathBuf::from(&path);
    if let Some(parent) = file.parent() {
        if !parent.as_os_str().is_empty() {
            fs::create_dir_all(parent).map_err(|e| format!("{}: {e}", parent.display()))?;
        }
    }
    fs::write(&file, text.as_bytes()).map_err(|e| format!("{}: {e}", file.display()))?;
    Ok(format!(
        "preset saved: {} weapon(s) → {}",
        preset.weapons.len(),
        file.display()
    ))
}

#[tauri::command]
pub fn load_weapon_preset(path: String) -> Result<WeaponPreset, String> {
    let file = PathBuf::from(&path);
    let text = fs::read_to_string(&file).map_err(|e| format!("{}: {e}", file.display()))?;
    let preset: WeaponPreset = serde_json::from_str(&text)
        .map_err(|e| format!("{path} is not a weapon preset: {e}"))?;
    if preset.app != PRESET_APP {
        return Err(format!(
            "{path} was written by '{}', not {PRESET_APP}",
            preset.app
        ));
    }
    if preset.version > PRESET_VERSION {
        return Err(format!(
            "{path} is version {} — this build understands up to {PRESET_VERSION}",
            preset.version
        ));
    }
    Ok(preset)
}

