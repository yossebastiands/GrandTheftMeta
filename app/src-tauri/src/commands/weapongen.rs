/// Every `OrderNumber` the target resource already uses, with the weapon id that owns it —
/// so an order only conflicts when a *different* weapon claims it (re-writing or growing a
/// pack must not trip over its own entries). The original tool kept a counter file instead.
pub(crate) fn collect_existing_orders(out: &Path) -> BTreeMap<u32, String> {
    let mut orders: BTreeMap<u32, String> = BTreeMap::new();
    for entry in WalkDir::new(out).follow_links(false).into_iter().flatten() {
        if !entry.file_type().is_file() {
            continue;
        }
        let name = entry.file_name().to_string_lossy().to_ascii_lowercase();
        if !(name.starts_with("weapons") && name.ends_with(".meta")) {
            continue;
        }
        let Ok(text) = fs::read_to_string(entry.path()) else {
            continue;
        };
        // reuse the catalogue parser: it already matches `<Slot>` to its `SlotNavigateOrder`
        if let Ok(templates) = super::weapontemplates::parse_template_items(&text, "", "") {
            for t in templates {
                if let Ok(order) = t.slot_order.parse::<u32>() {
                    orders.insert(order, t.id);
                }
            }
        }
    }
    orders
}

/// Component names already declared by the resource, with the weapon folder that owns
/// them (`metas/<slug>/components/<NAME>/weaponcomponents.meta`). Two weapons declaring the
/// same component silently override each other, so a collision with another owner blocks.
pub(crate) fn collect_existing_components(out: &Path) -> BTreeMap<String, String> {
    let mut components: BTreeMap<String, String> = BTreeMap::new();
    for entry in WalkDir::new(out).follow_links(false).into_iter().flatten() {
        if !entry.file_type().is_file() {
            continue;
        }
        let name = entry.file_name().to_string_lossy().to_ascii_lowercase();
        if !(name.starts_with("weaponcomponents") && name.ends_with(".meta")) {
            continue;
        }
        let path = entry.path();
        let parts: Vec<String> = path
            .components()
            .map(|c| c.as_os_str().to_string_lossy().to_string())
            .collect();
        let owner = parts
            .iter()
            .rposition(|p| p.eq_ignore_ascii_case("components"))
            .and_then(|i| i.checked_sub(1))
            .map(|i| parts[i].clone())
            .unwrap_or_default();
        let Ok(text) = fs::read_to_string(path) else {
            continue;
        };
        if let Ok(items) = super::weapontemplates::parse_component_items(&text, "", "") {
            for c in items {
                components.insert(c.name, owner.clone());
            }
        }
    }
    components
}

/// A weapon that is already in the resource keeps the order it was given last time. Without
/// this, re-writing a pack with `overwrite` would hand the same weapon a fresh order on every
/// run (423, 424, 425 …), so the slot order of a weapon would depend on how often it was saved.
pub(crate) fn adopt_existing_orders(
    specs: &mut [WeaponSpec],
    existing: &BTreeMap<u32, String>,
) -> usize {
    let mut own: BTreeMap<&str, u32> = BTreeMap::new();
    for (order, id) in existing {
        own.entry(id.as_str()).or_insert(*order);
    }
    let mut adopted = 0;
    for spec in specs.iter_mut() {
        if spec.slot_order.is_none() {
            if let Some(order) = own.get(spec.id.as_str()) {
                spec.slot_order = Some(*order);
                adopted += 1;
            }
        }
    }
    adopted
}

/// Give every weapon that has no slot order the next free one. Mutates the specs so the
/// build and the plan agree, and returns human-readable notes for the plan.
pub(crate) fn allocate_slot_orders(specs: &mut [WeaponSpec], existing: &[u32]) -> Vec<String> {
    let mut taken: BTreeSet<u32> = existing.iter().copied().collect();
    // Two passes: an explicit order anywhere in the pack is never handed out again, so
    // adding a weapon next to a hand-picked 423 gives 424 rather than the vanilla 300.
    for spec in specs.iter() {
        if let Some(order) = spec.slot_order {
            taken.insert(order);
        }
    }
    let mut next = taken
        .iter()
        .next_back()
        .copied()
        .map(|m| m + 1)
        .unwrap_or(DEFAULT_SLOT_ORDER);
    let mut notes = Vec::new();
    for spec in specs.iter_mut() {
        if spec.slot_order.is_none() {
            while taken.contains(&next) {
                next += 1;
            }
            spec.slot_order = Some(next);
            notes.push(format!(
                "{} → slot order {next} (allocated after the orders already in use)",
                spec.id
            ));
            taken.insert(next);
            next += 1;
        }
    }
    notes
}

/// Cross-weapon problems in one pack. Duplicates that break the resource are conflicts;
/// cosmetic collisions are warnings. Pure so the rules are unit tested.
pub(crate) fn pack_conflicts(
    entries: &[PackEntry],
    existing_orders: &BTreeMap<u32, String>,
    existing_components: &BTreeMap<String, String>,
) -> (Vec<String>, Vec<String>) {
    let mut conflicts: BTreeSet<String> = BTreeSet::new();
    let mut warnings: BTreeSet<String> = BTreeSet::new();
    let mut ids: BTreeSet<&str> = BTreeSet::new();
    let mut slugs: BTreeMap<&str, &str> = BTreeMap::new();
    let mut orders: BTreeMap<u32, &str> = BTreeMap::new();
    let mut labels: BTreeMap<&str, &str> = BTreeMap::new();
    let mut models: BTreeMap<&str, &str> = BTreeMap::new();
    let mut components: BTreeMap<&str, &str> = BTreeMap::new();

    for e in entries {
        if !ids.insert(&e.id) {
            conflicts.insert(format!("duplicate weapon id {} in the pack", e.id));
        }
        if let Some(other) = slugs.insert(&e.slug, &e.id) {
            conflicts.insert(format!(
                "{other} and {} both map to the resource folder 'metas/{}' — give them different ids",
                e.id, e.slug
            ));
        }
        if let Some(order) = e.order {
            // another weapon already owns this order in the resource…
            if let Some(owner) = existing_orders.get(&order) {
                if owner != &e.id {
                    conflicts.insert(format!(
                        "{} uses slot order {order}, which {owner} already uses in the target resource",
                        e.id
                    ));
                }
            }
            // …or a sibling in this very pack does
            if let Some(other) = orders.insert(order, &e.id) {
                if other != e.id {
                    conflicts.insert(format!("slot order {order} is used by both {other} and {}", e.id));
                }
            }
        }
        if let Some(other) = labels.insert(&e.label, &e.id) {
            if other != e.id {
                warnings.insert(format!("{} and {other} share the display name '{}'", e.id, e.label));
            }
        }
        if let Some(model) = e.model.as_deref() {
            if let Some(other) = models.insert(model, &e.id) {
                if other != e.id {
                    warnings.insert(format!("{other} and {} both point at the model {model}", e.id));
                }
            }
        }
        for c in &e.components {
            if let Some(other) = components.insert(c, &e.id) {
                if other != e.id {
                    conflicts.insert(format!("component {c} is declared by both {other} and {}", e.id));
                }
            }
            if let Some(owner) = existing_components.get(c) {
                if owner != &e.slug {
                    conflicts.insert(format!(
                        "component {c} already exists in the resource under metas/{owner}/ — a second copy would override it",
                    ));
                }
            }
        }
    }
    (conflicts.into_iter().collect(), warnings.into_iter().collect())
}

struct BuiltPack {
    weapons: Vec<(WeaponSpec, Built)>,
    conflicts: Vec<String>,
    warnings: Vec<String>,
    allocations: Vec<String>,
}

fn build_pack(pack: &WeaponPackSpec, out: &Path) -> Result<BuiltPack, String> {
    if pack.weapons.is_empty() {
        return Err("the pack has no weapons".into());
    }
    let existing_orders = collect_existing_orders(out);
    let existing_components = collect_existing_components(out);
    let mut specs = pack.weapons.clone();
    let order_list: Vec<u32> = existing_orders.keys().copied().collect();
    adopt_existing_orders(&mut specs, &existing_orders);
    let allocations = allocate_slot_orders(&mut specs, &order_list);

    let mut weapons: Vec<(WeaponSpec, Built)> = Vec::new();
    let mut conflicts: Vec<String> = Vec::new();
    let mut warnings: Vec<String> = Vec::new();
    let mut entries: Vec<PackEntry> = Vec::new();
    for spec in specs {
        let built = build_weapon(&spec);
        entries.push(PackEntry {
            id: spec.id.clone(),
            slug: weapon_slug(&spec.id),
            label: spec.display_name.clone(),
            order: spec.slot_order,
            model: spec.model.clone().or_else(|| {
                built
                    .as_ref()
                    .ok()
                    .and_then(|_| spec.model.clone())
            }),
            components: spec.components.iter().map(|c| c.name.clone()).collect(),
        });
        match built {
            Ok(b) => {
                conflicts.extend(b.conflicts.iter().map(|c| format!("{}: {c}", spec.id)));
                warnings.extend(b.warnings.iter().map(|w| format!("{}: {w}", spec.id)));
                weapons.push((spec, b));
            }
            Err(e) => conflicts.push(format!("{}: {e}", spec.id)),
        }
    }
    let (duplicates, cosmetic) = pack_conflicts(&entries, &existing_orders, &existing_components);
    conflicts.extend(duplicates);
    warnings.extend(cosmetic);
    Ok(BuiltPack { weapons, conflicts, warnings, allocations })
}

/// Dry run for a whole pack: one plan per weapon plus the shared files, duplicates,
/// allocated slot orders and blockers. Never writes.
#[tauri::command]
pub fn preview_weapon_pack(pack: WeaponPackSpec, out_folder: String) -> Result<PackPlan, String> {
    let out = PathBuf::from(&out_folder);
    let built = build_pack(&pack, &out)?;

    let mut total = 0usize;
    let mut weapons: Vec<ExportPlan> = Vec::new();
    for (spec, b) in &built.weapons {
        let mut plan = plan_for(b, &out, &weapon_slug(&spec.id));
        // the manifest and the label list are resource-wide: reported once in `shared_files`
        plan.files.retain(|f| f.kind != "manifest" && f.kind != "lua");
        plan.total_bytes = plan.files.iter().map(|f| f.bytes).sum();
        plan.conflicts
            .extend(target_conflicts(&out, spec, false).into_iter().map(|c| format!("{}: {c}", spec.id)));
        total += plan.total_bytes;
        weapons.push(plan);
    }

    let manifest = manifest_text();
    let lua: String = pack
        .weapons
        .iter()
        .map(|s| lua_entry(&s.id, &s.display_name))
        .collect();
    let manifest_path = out.join("fxmanifest.lua");
    let lua_path = out.join("cl_weaponNames.lua");
    let shared_files = vec![
        PlannedFile {
            path: manifest_path.to_string_lossy().into_owned(),
            action: if manifest_path.is_file() { "update" } else { "create" }.into(),
            kind: "manifest".into(),
            bytes: manifest.len(),
        },
        PlannedFile {
            path: lua_path.to_string_lossy().into_owned(),
            action: if lua_path.is_file() { "append" } else { "create" }.into(),
            kind: "lua".into(),
            bytes: lua.len(),
        },
    ];
    total += manifest.len() + lua.len();

    Ok(PackPlan {
        out_root: out.to_string_lossy().into_owned(),
        weapons,
        shared_files,
        conflicts: built.conflicts,
        warnings: built.warnings,
        allocations: built.allocations,
        total_bytes: total,
    })
}

/// Commit a whole pack into one resource. Adds weapons to an existing GTM-written
/// resource (that is how a pack grows); refuses while any conflict exists.
#[tauri::command]
pub fn write_weapon_pack(
    pack: WeaponPackSpec,
    out_folder: String,
    overwrite: bool,
) -> Result<PackWriteReport, String> {
    let out = PathBuf::from(&out_folder);
    let built = build_pack(&pack, &out)?;

    let mut conflicts = built.conflicts.clone();
    for (spec, b) in &built.weapons {
        conflicts.extend(b.conflicts.iter().map(|c| format!("{}: {c}", spec.id)));
        conflicts
            .extend(target_conflicts(&out, spec, overwrite).into_iter().map(|c| format!("{}: {c}", spec.id)));
    }
    if !conflicts.is_empty() {
        return Err(conflicts.join("\n"));
    }

    fs::create_dir_all(&out).map_err(|e| format!("{}: {e}", out.display()))?;
    let mut report = PackWriteReport {
        out_root: out.to_string_lossy().into_owned(),
        weapons: built.weapons.iter().map(|(s, _)| s.id.clone()).collect(),
        ..Default::default()
    };

    // --- resource-wide files, written once -------------------------------
    let manifest = out.join("fxmanifest.lua");
    let manifest_body = manifest_text();
    fs::write(&manifest, &manifest_body).map_err(|e| format!("{}: {e}", manifest.display()))?;
    report.bytes += manifest_body.len();
    report.written.push(manifest.to_string_lossy().into_owned());

    let lua = out.join("cl_weaponNames.lua");
    let mut lua_text = fs::read_to_string(&lua).unwrap_or_else(|_| lua_header());
    for (spec, _) in &built.weapons {
        if lua_text.contains(&format!("AddTextEntry(\"{}\"", spec.id)) {
            report.skipped.push(format!("{}.", spec.id));
            continue;
        }
        let entry = lua_entry(&spec.id, &spec.display_name);
        lua_text.push_str(&entry);
        report.bytes += entry.len();
    }
    fs::write(&lua, &lua_text).map_err(|e| format!("{}: {e}", lua.display()))?;
    report.written.push(lua.to_string_lossy().into_owned());

    // --- per weapon ------------------------------------------------------
    for (spec, b) in &built.weapons {
        let folder = weapon_slug(&spec.id);
        for (rel, kind, content) in &b.files {
            if kind == "manifest" || kind == "lua" {
                continue;
            }
            let path = out.join(rel);
            if let Some(parent) = path.parent() {
                fs::create_dir_all(parent).map_err(|e| format!("{}: {e}", parent.display()))?;
            }
            fs::write(&path, content).map_err(|e| format!("{}: {e}", path.display()))?;
            report.bytes += content.len();
            report.written.push(path.to_string_lossy().into_owned());
        }
        for src in &b.stream {
            let source = Path::new(src);
            let target = out.join("stream").join(&folder).join(source.file_name().unwrap_or_default());
            if let Some(parent) = target.parent() {
                fs::create_dir_all(parent).map_err(|e| format!("{}: {e}", parent.display()))?;
            }
            fs::copy(source, &target).map_err(|e| format!("{}: {e}", target.display()))?;
            report.bytes += fs::metadata(&target).map(|m| m.len() as usize).unwrap_or(0);
            report.copied.push(target.to_string_lossy().into_owned());
        }
    }

    report.notes.push(format!(
        "pack written: {} weapon(s), {} file(s), {} streamed asset(s) → {}",
        built.weapons.len(),
        report.written.len(),
        report.copied.len(),
        out.display()
    ));
    report.notes.extend(built.allocations.iter().cloned());
    Ok(report)
}

