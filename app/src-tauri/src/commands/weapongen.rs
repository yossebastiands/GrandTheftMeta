/// `WEAPON_GLOCK17` → `glock17` (resource sub-folder + stream folder name).
pub(crate) fn weapon_slug(id: &str) -> String {
    let tail = id.strip_prefix("WEAPON_").unwrap_or(id);
    let mut out: String = tail
        .chars()
        .map(|c| if c.is_ascii_alphanumeric() { c.to_ascii_lowercase() } else { '_' })
        .collect();
    while out.contains("__") {
        out = out.replace("__", "_");
    }
    out.trim_matches('_').to_string()
}

