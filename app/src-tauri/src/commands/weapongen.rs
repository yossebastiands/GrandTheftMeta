/// One component as it will appear in the weapon's `<AttachPoints>`.
#[derive(Debug, Clone)]
pub(crate) struct AttachSpec {
    pub name: String,
    /// Bone on the weapon (`WAPClip`, `WAPSupp`, …) — read from the component itself.
    pub bone: String,
    pub default: bool,
}

/// One attachment **slot** = one bone on the weapon, with its ordered alternatives. This is
/// what the weapon wheel cycles through, and what a hand-made pack with a real mod selection
/// (6 clips, 2 frames, 8 stocks …) is made of.
#[derive(Debug, Clone, PartialEq, Eq)]
pub(crate) struct AttachSlot {
    pub bone: String,
    pub options: Vec<AttachOption>,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub(crate) struct AttachOption {
    pub name: String,
    pub default: bool,
}

/// Generate `weaponarchetypes.meta` from the streamed drawables: one `CWeaponModelInfo`
/// per drawable (`_hi` LODs and textures excluded), `lodDist` 500 for the weapon's own
/// model and 300 for the rest — the rule the original tool used.
pub(crate) fn build_weaponarchetypes(assets: &[WeaponAsset], main: Option<&str>) -> String {
    let mut text = archetypes_skeleton();
    let mut seen: BTreeSet<String> = BTreeSet::new();
    for asset in assets.iter().filter(|a| a.kind == "drawable" && a.role != "lod") {
        if !seen.insert(asset.drawable.clone()) {
            continue;
        }
        let lod = if Some(asset.drawable.as_str()) == main { "500" } else { "300" };
        let item = format!(
            "<Item>\n\t<modelName>{0}</modelName>\n\t<txdName>{0}</txdName>\n\t\
             <ptfxAssetName>NULL</ptfxAssetName>\n\t<lodDist value=\"{lod}\" />\n</Item>",
            asset.drawable
        );
        if let Some(next) = insert_element(&text, &parse_path("InitDatas").unwrap(), InsertAt::Last, &item)
        {
            text = next;
        }
    }
    text
}

/// Group the per-component records into slots the way the vanilla files (and every hand-made
/// pack we measured) do: **one `<Item>` per `WeaponAttachBone`**, every alternative nested as a
/// `<Components>` option in the order the user queued them (that order is the cycle order in
/// game). The original tool wrote one `<Item>` per *component* instead, so a weapon with two
/// clips carried two sibling `WAPClip` blocks — same triples, degenerate structure.
///
/// Returns `(slots, warnings)`. Bone order = order of first appearance, so the output is stable.
pub(crate) fn group_attach_slots(specs: &[AttachSpec]) -> (Vec<AttachSlot>, Vec<String>) {
    let mut slots: Vec<AttachSlot> = Vec::new();
    let mut warnings: Vec<String> = Vec::new();
    for spec in specs {
        if spec.bone.trim().is_empty() {
            continue; // already warned about by the caller
        }
        match slots.iter_mut().find(|s| s.bone == spec.bone) {
            Some(slot) => slot.options.push(AttachOption { name: spec.name.clone(), default: spec.default }),
            None => slots.push(AttachSlot {
                bone: spec.bone.clone(),
                options: vec![AttachOption { name: spec.name.clone(), default: spec.default }],
            }),
        }
    }
    for slot in &slots {
        let defaults = slot.options.iter().filter(|o| o.default).count();
        if defaults > 1 {
            warnings.push(format!(
                "slot {} has {defaults} options marked as default — only one can be equipped, the others are alternatives",
                slot.bone
            ));
        }
    }
    (slots, warnings)
}

/// One `<AttachPoints>` entry: the bone plus every option of that slot.
pub(crate) fn attach_point_block(slot: &AttachSlot) -> String {
    let mut text = format!(
        "<Item>\n\t<AttachBone>{}</AttachBone>\n\t<Components>",
        slot.bone
    );
    for option in &slot.options {
        text.push_str(&format!(
            "\n\t\t<Item>\n\t\t\t<Default value=\"{}\" />\n\t\t\t<Name>{}</Name>\n\t\t</Item>",
            if option.default { "true" } else { "false" },
            option.name
        ));
    }
    text.push_str("\n\t</Components>\n</Item>");
    text
}

/// Build the exported `weapons.meta`: the template's weapon entry cloned + renamed, the
/// slot/order entry minted, the requested values patched and `<AttachPoints>` generated.
pub(crate) fn build_weapons_meta(
    template_text: &str,
    template_id: &str,
    spec: &WeaponSpec,
    slots: &[AttachSlot],
    model: Option<&str>,
) -> Result<(String, Vec<String>, Vec<String>), String> {
    let (start, end) = item_span_by_name(template_text, template_id)
        .ok_or_else(|| format!("{template_id} not found in {}", spec.template_meta_path))?;
    let renamed = clone_span(template_text, (start, end), &[(template_id, spec.id.as_str())]);

    let mut text = weapons_skeleton();
    let order = spec.slot_order.unwrap_or(DEFAULT_SLOT_ORDER);
    let slot = format!("SLOT_{}", spec.id);
    let entry = format!(
        "<Item>\n\t<OrderNumber value=\"{order}\" />\n\t<Entry>{slot}</Entry>\n</Item>"
    );
    text = insert_element(&text, &parse_path("SlotNavigateOrder/0/WeaponSlots").unwrap(), InsertAt::Last, &entry)
        .ok_or("cannot build SlotNavigateOrder")?;
    text = insert_element(&text, &parse_path("Infos/0/Infos").unwrap(), InsertAt::Last, &renamed)
        .ok_or("cannot insert the weapon entry")?;

    let base = "Infos/0/Infos/0";
    let mut edits: Vec<String> = Vec::new();
    let mut warnings: Vec<String> = Vec::new();

    edits.push(format!("Name → {}", spec.id));
    try_set_text(&mut text, &format!("{base}/Name"), &spec.id);
    edits.push(format!("Slot → {slot} (SlotNavigateOrder entry + order {order})"));
    try_set_text(&mut text, &format!("{base}/Slot"), &slot);
    edits.push(format!("HumanNameHash → {} (label comes from cl_weaponNames.lua)", spec.id));
    try_set_text(&mut text, &format!("{base}/HumanNameHash"), &spec.id);

    if let Some(model) = model {
        edits.push(format!("Model → {model}"));
        try_set_text(&mut text, &format!("{base}/Model"), model);
    }
    for (label, elem, opt) in [
        ("Audio", "Audio", spec.audio.as_deref()),
        ("DamageType", "DamageType", spec.damage_type.as_deref()),
        ("FireType", "FireType", spec.fire_type.as_deref()),
    ] {
        if let Some(v) = opt {
            edits.push(format!("{label} → {v}"));
            try_set_text(&mut text, &format!("{base}/{elem}"), v);
        }
    }
    for (label, elem, attr, opt) in [
        ("AmmoInfo ref", "AmmoInfo", "ref", spec.ammo_ref.as_deref()),
        ("Damage", "Damage", "value", spec.damage.as_deref()),
        ("WeaponRange", "WeaponRange", "value", spec.range.as_deref()),
        ("ClipSize", "ClipSize", "value", spec.clip_size.as_deref()),
        (
            "HeadShotDamageModifierPlayer",
            "HeadShotDamageModifierPlayer",
            "value",
            spec.headshot_modifier.as_deref(),
        ),
        ("AnimReloadRate", "AnimReloadRate", "value", spec.reload_rate.as_deref()),
    ] {
        if let Some(v) = opt {
            edits.push(format!("{label} → {v}"));
            try_set_attr(&mut text, &format!("{base}/{elem}"), attr, v);
        }
    }

    if !slots.is_empty() {
        // The cloned entry carries the template's own `<AttachPoints>` (a real pack's meta has
        // them; the toolkit's templates ship the block empty). Replace them — appending our
        // slots would leave every bone the template used listed twice.
        let path = format!("{base}/AttachPoints");
        let blocks = text.matches("<AttachBone>").count();
        let inherited = text.matches("<Default value=").count();
        if let Some(cleared) = clear_children(&text, &parse_path(&path).unwrap()) {
            text = cleared;
            edits.push(format!(
                "AttachPoints → replaced the template's own {blocks} slot block(s), {inherited} option(s)"
            ));
        } else if blocks > 0 {
            warnings.push(format!(
                "the template already declares {blocks} attachment block(s) outside <AttachPoints> — check the generated weapon entry"
            ));
        }
        let options: usize = slots.iter().map(|s| s.options.len()).sum();
        edits.push(format!(
            "AttachPoints → {} slot(s) on {} bone(s), {options} option(s)",
            slots.len(),
            slots.iter().map(|s| s.bone.clone()).collect::<BTreeSet<_>>().len()
        ));
        for slot in slots {
            text = insert_element(&text, &parse_path(&path).unwrap(), InsertAt::Last, &attach_point_block(slot))
                .ok_or("cannot build AttachPoints")?;
        }
    } else {
        let blocks = text.matches("<AttachBone>").count();
        if blocks > 0 {
            warnings.push(format!(
                "no components were chosen, so the weapon keeps the template's own {blocks} attachment slot block(s)"
            ));
        }
    }

    Ok((text, edits, warnings))
}

/// Build one exported `weaponcomponents.meta` from a source component entry.
/// Returns `(text, weapon attach bone, edits)`.
pub(crate) fn build_component_meta(
    source_text: &str,
    source_name: &str,
    spec: &ComponentSpec,
) -> Result<(String, String, Vec<String>), String> {
    let (start, end) = item_span_by_name(source_text, source_name)
        .ok_or_else(|| format!("{source_name} not found in {}", spec.source_file))?;
    let rename: Vec<(&str, &str)> = if spec.name == source_name {
        Vec::new()
    } else {
        vec![(source_name, spec.name.as_str())]
    };
    let cloned = clone_span(source_text, (start, end), &rename);
    let mut text = insert_element(&component_skeleton(), &parse_path("Infos").unwrap(), InsertAt::Last, &cloned)
        .ok_or("cannot build the component file")?;

    let base = "Infos/0";
    let mut edits = Vec::new();
    if spec.name != source_name {
        edits.push(format!("component {source_name} → {}", spec.name));
    }
    if let Some(model) = &spec.model {
        edits.push(format!("component {} Model → {model}", spec.name));
        try_set_text(&mut text, &format!("{base}/Model"), model);
    }
    if let Some(clip) = &spec.clip_size {
        edits.push(format!("component {} ClipSize → {clip}", spec.name));
        try_set_attr(&mut text, &format!("{base}/ClipSize"), "value", clip);
    }
    let bone = read_text_at(&text, &format!("{base}/WeaponAttachBone")).unwrap_or_default();
    Ok((text, bone, edits))
}

/// Patch `<AnimFireRateModifier>` in every personality set of a `weaponanimations.meta`.
/// Returns how many sets were changed.
pub(crate) fn set_anim_fire_rate(text: &mut String, value: &str) -> usize {
    let mut patched = 0;
    for i in 0..16 {
        let path = format!("WeaponAnimationsSets/{i}/WeaponAnimations/0/AnimFireRateModifier");
        if try_set_attr(text, &path, "value", value) {
            patched += 1;
        } else if i > 0 {
            break;
        }
    }
    patched
}

