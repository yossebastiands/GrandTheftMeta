//! Weapon pack generator — P2: build ONE add-on weapon resource from a base template.
//!
//! Design rules (see `Dev-Notes/MyApps/vWeaponsToolkit/vWeaponsToolkit-1.0.3-ANALYSIS.md` §10):
//!
//! * **Surgical, never re-serialised.** The template's weapon entry is cloned *as text*
//!   (`textnav::clone_span`) and patched leaf-by-leaf; `weaponanimations` /
//!   `pedpersonality` are the template's own bytes with the weapon ids retargeted. The
//!   diff against the source stays tiny and hand-tuned whitespace/comments survive.
//! * **A weapon id is not a token you can blanket-rename.** Inside `weapons.meta`
//!   `WEAPON_PISTOL` also appears as `<ReticuleStyleHash>` and
//!   `WEAPON_EFFECT_GROUP_*` as `<EffectGroup>`, so only `<Name>`/`<Slot>`/
//!   `SlotNavigateOrder/Entry`/`<HumanNameHash>` are rewritten — exactly the surface the
//!   original tool touched (verified against a real generated weapon). Whole-file
//!   retargeting happens *only* in the animation/personality files, whose only
//!   `WEAPON_*` tokens are weapon ids (measured).
//! * **A shared vanilla file is refused, not guessed.** Cloning `weaponanimations.meta`
//!   only makes sense per weapon, so a file naming more than `MAX_TEMPLATE_IDS` weapons
//!   is a blocker with an actionable message — P2 ships single-weapon resources.
//! * **Nothing is written without a plan.** `preview_weapon_export` computes exactly what
//!   the writer would do (per-file action, bytes, retargets, conflicts) and the writer
//!   refuses to run while any conflict remains.

