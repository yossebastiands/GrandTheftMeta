/// A file naming more weapons than this is a shared/vanilla file, not a per-weapon template.
pub(crate) const MAX_TEMPLATE_IDS: usize = 3;
/// Order number used when the spec does not set one (vanilla weapons use 300-ish values).
pub(crate) const DEFAULT_SLOT_ORDER: u32 = 300;
/// Marker written into the manifest so the generator only ever updates its *own* output.
pub(crate) const MANIFEST_MARKER: &str = "generated by GrandTheftMeta (weapon pack generator)";

