fn id_re() -> &'static Regex {
    static RE: OnceLock<Regex> = OnceLock::new();
    RE.get_or_init(|| Regex::new(r"^WEAPON_[A-Z0-9_]+$").expect("weapon id regex"))
}

/// `WEAPON_EFFECT_GROUP_*` and friends are values, not weapon references.
pub(crate) fn is_pseudo_weapon_token(id: &str) -> bool {
    let up = id.to_ascii_uppercase();
    up.starts_with("WEAPON_EFFECT_") || up.contains("EFFECT_GROUP")
}

/// Every weapon id in a file with its occurrence count (commented-out ones ignored).
pub(crate) fn weapon_ids_in_file(text: &str) -> BTreeMap<String, usize> {
    let re = Regex::new(r"WEAPON_[A-Za-z0-9_]+").unwrap();
    let mut out: BTreeMap<String, usize> = BTreeMap::new();
    for m in re.find_iter(&masked(text)) {
        let id = m.as_str().to_string();
        if is_pseudo_weapon_token(&id) {
            continue;
        }
        *out.entry(id).or_insert(0) += 1;
    }
    out
}

/// Retarget *every* weapon id in a per-weapon template file to `new_id`.
pub(crate) fn retarget_file(text: &str, new_id: &str) -> String {
    let ids: Vec<String> = weapon_ids_in_file(text).into_keys().collect();
    let pairs: Vec<(&str, &str)> = ids.iter().map(|i| (i.as_str(), new_id)).collect();
    retarget_identifiers(text, &pairs)
}

/// Byte span of the innermost `<Item>` whose text contains `<Name>name</Name>`
/// (comment-aware, nesting-aware). Innermost matters: a wrapper item such as
/// `Infos/0` also *contains* the weapon entry — and everything commented out beside it.
pub(crate) fn item_span_by_name(text: &str, name: &str) -> Option<(usize, usize)> {
    let scan = masked(text);
    let re = Regex::new(r"<Item\b").unwrap();
    let needle = format!("<Name>{name}</Name>");
    let mut best: Option<(usize, usize)> = None;
    for hit in re.find_iter(&scan) {
        let start = hit.start();
        let gt = start + scan[start..].find('>')?;
        if scan[start..=gt].ends_with("/>") {
            continue;
        }
        let Some(end) = find_matching_close(text, gt + 1) else {
            continue;
        };
        if !text[start..end].contains(&needle) {
            continue;
        }
        if best.is_none_or(|(s, e)| end - start < e - s) {
            best = Some((start, end));
        }
    }
    best
}

fn read_text_at(text: &str, path: &str) -> Option<String> {
    let span = node_span(text, &parse_path(path).ok()?)?;
    let (lo, hi) = span.interior();
    Some(text[lo..hi].trim().to_string())
}

/// Read a text leaf at a path. Test-only helper (the generator writes through `try_set_*`), and
/// the parity tests read the shipped export through it.
#[cfg(test)]
fn read_attr_at(text: &str, path: &str, attr: &str) -> Option<String> {
    let span = node_span(text, &parse_path(path).ok()?)?;
    let tag = &text[span.open_start..span.open_end];
    Regex::new(&format!(r#"\b{}\s*=\s*"([^"]*)""#, regex::escape(attr)))
        .ok()?
        .captures(tag)
        .and_then(|c| c.get(1).map(|m| m.as_str().to_string()))
}

/// Set an element's text. Returns false when the element is absent (a spec knob pointing
/// at a field the template does not have is a warning, not a failure).
fn try_set_text(text: &mut String, path: &str, value: &str) -> bool {
    let Ok(steps) = parse_path(path) else { return false };
    let Some(span) = node_span(text, &steps) else { return false };
    let Some(close) = span.close_start else { return false };
    *text = replace_text(text, span.open_end, close, value);
    true
}

fn try_set_attr(text: &mut String, path: &str, attr: &str, value: &str) -> bool {
    let Ok(steps) = parse_path(path) else { return false };
    let Some(span) = node_span(text, &steps) else { return false };
    *text = replace_attr_value(text, span.open_start, span.open_end, attr, value);
    true
}

