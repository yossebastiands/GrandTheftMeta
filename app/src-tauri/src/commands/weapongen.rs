    /// `(bone, name, default)` for every option in an `<AttachPoints>` block, whatever shape the
    /// file uses: the vanilla/grouped form (one `<Item>` per bone) or the original tool's flat
    /// form (one `<Item>` per component). An option belongs to the bone that precedes it.
    fn triples(text: &str) -> BTreeSet<(String, String, String)> {
        let bone_re = Regex::new(r"<AttachBone>([^<]+)</AttachBone>").unwrap();
        // the original's serialiser writes `value="false"/>` where ours keeps the template's
        // `" />`, so the white space before `/>` is optional here
        let option_re =
            Regex::new(r#"<Default value="(true|false)"\s*/>\s*<Name>([^<]+)</Name>"#).unwrap();
        let bones: Vec<_> = bone_re.captures_iter(text).collect();
        let mut out = BTreeSet::new();
        for (i, bone) in bones.iter().enumerate() {
            let end = bones.get(i + 1).map(|b| b.get(0).unwrap().start()).unwrap_or(text.len());
            for option in option_re.captures_iter(&text[bone.get(0).unwrap().end()..end]) {
                out.insert((
                    bone[1].to_string(),
                    option[2].to_string(),
                    option[1].to_string(),
                ));
            }
        }
        out
    }

    /// `(bone, option names in file order)` per `<AttachPoints>` block, in file order — the
    /// shape check. The grouped/vanilla form gives one entry per bone; the original tool's flat
    /// form gives one entry per component, so the same bone can appear several times.
    fn shape(text: &str) -> Vec<(String, Vec<String>)> {
        let bone_re = Regex::new(r"<AttachBone>([^<]+)</AttachBone>").unwrap();
        let option_re =
            Regex::new(r#"<Default value="(true|false)"\s*/>\s*<Name>([^<]+)</Name>"#).unwrap();
        let bones: Vec<_> = bone_re.captures_iter(text).collect();
        let mut out = Vec::new();
        for (i, bone) in bones.iter().enumerate() {
            let end = bones.get(i + 1).map(|b| b.get(0).unwrap().start()).unwrap_or(text.len());
            let body = &text[bone.get(0).unwrap().end()..end];
            out.push((
                bone[1].to_string(),
                option_re.captures_iter(body).map(|c| c[2].to_string()).collect(),
            ));
        }
        out
    }

    /// The semantic view of `shape`: bone → options, merging repeated blocks (a bone that the
    /// flat shape split across two blocks is still one slot to the game).
    fn slots_of(text: &str) -> BTreeMap<String, Vec<String>> {
        let mut slots: BTreeMap<String, Vec<String>> = BTreeMap::new();
        for (bone, options) in shape(text) {
            slots.entry(bone).or_default().extend(options);
        }
        slots
    }

